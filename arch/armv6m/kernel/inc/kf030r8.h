#define K_F030R8_RCC_CR_HSION (1UL << 0U)
#define K_F030R8_RCC_CR_HSIRDY (1UL << 1U)
#define K_F030R8_RCC_CR_PLLON (1UL << 24U)
#define K_F030R8_RCC_CR_PLLRDY (1UL << 25U)

