#define K_F030R8_RCC_CFGR_PLLSRC (1UL << 16U)
#define K_F030R8_RCC_CFGR_PLLMUL_MASK (0xFUL << 18U)
#define K_F030R8_RCC_CFGR_PLLMUL(value) (((ULONG)(value) - 2UL) << 18U)

#define K_F030R8_RCC_AHBENR_GPIOAEN (1UL << 17U)
#define K_F030R8_RCC_APB1ENR_USART2EN (1UL << 17U)

#define K_F030R8_FLASH_ACR K_F030R8_REG32(0x40022000UL)
#define K_F030R8_FLASH_ACR_LATENCY (1UL << 0U)
